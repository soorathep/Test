/** Lab 05 graduate investigations: calibration versus temperature transfer,
 * fixed-alpha identifiability and measurement sensitivity of fitted NRTL tau.
 * Pure functions on top of the shared course engines. */
import * as fitter from '../../labs/assets/lle-fit.js';
import * as engine from '../../labs/assets/stability.js';

export const LLE_GRADUATE_VERSION = '1.0.0';
export const ALPHAS = Object.freeze([0.2, 0.3, 0.47]);
export const TRUTH = fitter.TRUTH;
export const SYNTHETIC_T = 298.15;

const mean = a => a.reduce((v, x) => v + x, 0) / a.length;

/** Exact synthetic control: one tie line generated by the known NRTL parameters. */
export function syntheticRows() {
  const gap = engine.coexistence(TRUTH);
  return [{ T: SYNTHETIC_T, xAlpha: gap.xAlpha, xBeta: gap.xBeta }];
}

export function measuredRows(data, T) {
  const row = data.rows.find(r => Math.abs(r.T - T) < 1e-8);
  if (!row) throw new RangeError('Select a reported temperature.');
  return [{ T: row.T, xAlpha: row.xAlpha, xBeta: row.xBeta, uAlpha: row.expandedUncertaintyAlpha, uBeta: row.expandedUncertaintyBeta }];
}

/** Fit two tau at fixed alpha and reduce the result to reported quantities. */
export function fitSummary(rows, alpha, start = [1, 1]) {
  const r = fitter.fit(rows.map(({ T, xAlpha, xBeta }) => ({ T, xAlpha, xBeta })), { alpha, start, multistart: true });
  const p = r.parameters, d = r.diagnostics, b = d.binodal;
  let minScaledCurvature = null;
  try { minScaledCurvature = engine.spinodals(p).minScaledCurvature; } catch { /* reported as unavailable */ }
  return {
    alpha, tau12: p.tau12, tau21: p.tau21, parameters: p, objective: r.objective, muRMSE: r.chemicalPotentialRMSE,
    converged: r.converged, convergedStarts: r.runs.filter(run => run.converged).length, starts: r.runs.length, atBound: r.atBound,
    predictedAlpha: b?.xAlpha ?? null, predictedBeta: b?.xBeta ?? null, compositionRMSE: d.compositionRMSE, gapCount: d.gaps.length,
    predictedTPD: d.predictedTPD.map(t => t.minimum), observedTPD: d.observedTPD.map(t => t.minimum),
    resolved: d.resolved, message: d.message, singularValueRatio: r.sensitivity.singularValueRatio, minScaledCurvature,
    runs: r.runs.map(run => ({ start: run.start, tau12: run.parameters.tau12, tau21: run.parameters.tau21, objective: run.objective, converged: run.converged, compositionRMSE: run.diagnostic.compositionRMSE })),
    T: r.T, rows,
  };
}

/** Status a reader can act on: calibrated, converged-but-wrong, or no split. */
export function fitVerdict(summary) {
  if (summary.compositionRMSE === null) return { level: 'fail', text: 'The fitted parameters predict no verified liquid split, so the fit does not reproduce LLE even if the optimizer converged.' };
  if (summary.compositionRMSE > 0.01) return { level: 'fail', text: 'The optimizer converged, but the predicted coexisting liquids miss the data by ' + summary.compositionRMSE.toPrecision(3) + ' in mole fraction. Equal chemical potentials were not reached on the observed branch.' };
  return { level: 'pass', text: 'The fitted model reproduces the observed tie line on a globally supporting common tangent. With two equations and two τ values this is calibration, not validation.' };
}

/** tau(T) under a declared temperature assumption. */
export function transferParameters(p, T0, T, mode, second = null) {
  if (mode === 'constant') return { ...p };
  if (mode === 'inverse') return { ...p, tau12: p.tau12 * T0 / T, tau21: p.tau21 * T0 / T };
  if (mode === 'two-point') {
    if (!second) throw new Error('A second calibration temperature is required.');
    const b = key => (p[key] - second.p[key]) / (1 / T0 - 1 / second.T), a = key => p[key] - b(key) / T0;
    return { ...p, tau12: a('tau12') + b('tau12') / T, tau21: a('tau21') + b('tau21') / T };
  }
  throw new RangeError('Unknown temperature assumption.');
}

export const TRANSFER_LABELS = Object.freeze({ constant: 'Constant τ', inverse: 'τ ∝ 1/T', 'two-point': 'τ = a + b/T from two temperatures' });

/** A. Predict every reported tie line from a calibration at T0 (and T1 for a + b/T). */
export function temperatureTransfer(data, alpha, T0, T1 = null) {
  const base = fitSummary(measuredRows(data, T0), alpha);
  const second = T1 !== null && Math.abs(T1 - T0) > 1e-8 ? fitSummary(measuredRows(data, T1), alpha) : null;
  const modes = second ? ['constant', 'inverse', 'two-point'] : ['constant', 'inverse'];
  const calibration = new Set([T0, ...(second ? [T1] : [])]);
  const rows = data.rows.map(row => {
    const out = { T: row.T, xAlpha: row.xAlpha, xBeta: row.xBeta, uAlpha: row.expandedUncertaintyAlpha, uBeta: row.expandedUncertaintyBeta, calibration: calibration.has(row.T), predictions: {} };
    for (const mode of modes) {
      try {
        const p = transferParameters(base.parameters, T0, row.T, mode, second && { T: T1, p: second.parameters });
        if (![p.tau12, p.tau21].every(v => v >= -2 && v <= 6)) throw new RangeError('Transferred τ lies outside −2 to 6.');
        const gaps = engine.coexistenceGaps(p);
        const gap = gaps.sort((g, h) => ((g.xAlpha - row.xAlpha) ** 2 + (g.xBeta - row.xBeta) ** 2) - ((h.xAlpha - row.xAlpha) ** 2 + (h.xBeta - row.xBeta) ** 2))[0];
        out.predictions[mode] = gap ? { status: 'split', xAlpha: gap.xAlpha, xBeta: gap.xBeta, error: Math.sqrt(((gap.xAlpha - row.xAlpha) ** 2 + (gap.xBeta - row.xBeta) ** 2) / 2),
          withinU: Math.abs(gap.xAlpha - row.xAlpha) <= row.expandedUncertaintyAlpha && Math.abs(gap.xBeta - row.xBeta) <= row.expandedUncertaintyBeta } : { status: 'none' };
      } catch (error) { out.predictions[mode] = { status: 'failed', reason: error.message }; }
    }
    return out;
  });
  const summary = Object.fromEntries(modes.map(mode => {
    const held = rows.filter(r => !r.calibration), ok = held.map(r => r.predictions[mode]).filter(p => p.status === 'split');
    return [mode, { heldOut: held.length, predicted: ok.length, rmse: ok.length ? Math.sqrt(mean(ok.map(p => p.error ** 2))) : null, withinU: ok.filter(p => p.withinU).length,
      maxError: ok.length ? Math.max(...ok.map(p => p.error)) : null }];
  }));
  return { alpha, T0, T1: second ? T1 : null, base, second, modes, rows, summary };
}

/** B. Same tie line, three fixed alpha values. */
export function alphaStudy(rows, data = null, T0 = null) {
  return ALPHAS.map(alpha => {
    try {
      const s = fitSummary(rows, alpha), verdict = fitVerdict(s);
      let transfer = null;
      if (data && T0 !== null && verdict.level === 'pass') {
        const t = temperatureTransfer(data, alpha, T0);
        transfer = t.summary.inverse;
      }
      return { alpha, status: 'fitted', summary: s, verdict, transfer };
    } catch (error) { return { alpha, status: 'failed', reason: error.message }; }
  });
}

/** Normalize composition half-widths. */
export function normalizeBounds(raw, rows) {
  const r = rows[0], defaults = { xAlpha: r.uAlpha ?? 0.005, xBeta: r.uBeta ?? 0.005 };
  return Object.fromEntries(['xAlpha', 'xBeta'].map(key => {
    const v = raw?.[key] === undefined || raw[key] === '' ? defaults[key] : Number(raw[key]);
    if (!Number.isFinite(v) || v < 0 || v > 0.1) throw new RangeError('Each half-width must lie between 0 and 0.1 mol/mol.');
    return [key, v];
  }));
}

/** C. Refit after shifting the observed compositions within assumed bounds. */
export function measurementSensitivity(rows, alpha, rawBounds) {
  const bounds = normalizeBounds(rawBounds, rows), r = rows[0];
  const base = fitSummary(rows, alpha);
  const run = (label, dA, dB) => {
    const shifted = [{ T: r.T, xAlpha: r.xAlpha + dA, xBeta: r.xBeta + dB }];
    try {
      const s = fitSummary(shifted, alpha), v = fitVerdict(s);
      return { label, xAlpha: shifted[0].xAlpha, xBeta: shifted[0].xBeta, status: v.level === 'pass' ? 'fitted' : 'poor', tau12: s.tau12, tau21: s.tau21, compositionRMSE: s.compositionRMSE, reason: v.level === 'pass' ? '' : v.text };
    } catch (error) { return { label, xAlpha: shifted[0].xAlpha, xBeta: shifted[0].xBeta, status: 'failed', reason: error.message }; }
  };
  const a = bounds.xAlpha, b = bounds.xBeta;
  const oneAtATime = [run('x₁ᵅ − ' + a, -a, 0), run('x₁ᵅ + ' + a, a, 0), run('x₁ᵝ − ' + b, 0, -b), run('x₁ᵝ + ' + b, 0, b)];
  const corners = [[-1, -1], [-1, 1], [1, -1], [1, 1]].map(([i, j]) => run((i < 0 ? '−' : '+') + (j < 0 ? '−' : '+'), i * a, j * b));
  const good = [...oneAtATime, ...corners].filter(s => s.status === 'fitted');
  const range = key => good.length ? [Math.min(...good.map(s => s[key])), Math.max(...good.map(s => s[key]))] : null;
  return { alpha, bounds, base, oneAtATime, corners, accepted: good.length, total: 8, ranges: { tau12: range('tau12'), tau21: range('tau21') } };
}

/** Completeness check only; it does not grade reasoning. */
export function evidenceCheck(record) {
  const issues = [];
  if (!record.transfer) issues.push('Run investigation A with measured data.');
  if (!record.alpha) issues.push('Run the fixed-α comparison in investigation B.');
  if (!record.sensitivity) issues.push('Run the measurement scenarios in investigation C.');
  for (const [key, label] of [['calibration', 'Claim 1'], ['alpha', 'Claim 2'], ['measurement', 'Claim 3'], ['decision', 'Decision and next evidence']]) {
    const text = (record.notes?.[key] || '').trim();
    if (text.length < 40) issues.push(label + ' needs a fuller statement.');
    else if ((text.match(/\d/g) || []).length < 2) issues.push(label + ' should quote at least one calculated number.');
  }
  return { complete: issues.length === 0, issues };
}
